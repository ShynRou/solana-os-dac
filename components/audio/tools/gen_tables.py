#!/usr/bin/env python3
"""Generate core/aud_tables.c: the mixer's constant tables.

The mixer uses no floating point (task spec "Rules that keep it fast"), so
every curve it needs is computed here once and checked in. The output is
deterministic: the host tests' golden files depend on it.

    python3 components/audio/tools/gen_tables.py > components/audio/core/aud_tables.c
"""
import math


def row(vals, per=12):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def main():
    sine = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]
    pan_l = [round(32767 * math.cos(i / 128 * math.pi / 2)) for i in range(129)]
    pan_r = [round(32767 * math.sin(i / 128 * math.pi / 2)) for i in range(129)]
    semi = [round(65536 * 2 ** (i / 12)) for i in range(12)]
    frac = [round(65536 * 2 ** (i / 3072)) for i in range(256)]
    ccmul = [round(65536 * 10 ** ((v - 64) / 64)) for v in range(128)]
    print("// Generated by tools/gen_tables.py: do not edit.")
    print('#include "aud_tables.h"\n')
    print("// sin(2 pi i / 256) in Q15; entry 256 repeats entry 0 for interpolation.")
    print("const int16_t aud_sine[257] = {\n%s\n};\n" % row(sine))
    print("// Constant-power pan: index 0 hard left, 64 centre, 128 hard right (Q15).")
    print("const int16_t aud_pan_l[129] = {\n%s\n};\n" % row(pan_l))
    print("const int16_t aud_pan_r[129] = {\n%s\n};\n" % row(pan_r))
    print("// 2^(i/12) in Q16.")
    print("const uint32_t aud_semi[12] = {\n%s\n};\n" % row(semi))
    print("// 2^(i/3072) in Q16: 1/256 of a semitone.")
    print("const uint32_t aud_frac[256] = {\n%s\n};\n" % row(frac))
    print("// 10^((v-64)/64) in Q16: CC 72, 73, 75, 76, 78; 64 is 1.0, 0 is 0.1, 127 about 9.7.")
    print("const uint32_t aud_ccmul[128] = {\n%s\n};" % row(ccmul))


if __name__ == "__main__":
    main()
